#!/bin/bash
# Workflow 2 setup: one Vault Agent API proxy on a normal localhost URL.
# This demonstrates token automation only; any local process can reach the
# listener, so it deliberately makes no process-isolation claim.
set -euo pipefail
STAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${STAGE_DIR}/common.sh"

device="${1:-node01}"
domain="${2:-devices.lab.local}"
role="payments-app"
state_dir="/var/lib/vault-agent/single/tpm"
config="/etc/vault-proxy/single.hcl"
unit="/etc/systemd/system/vault-proxy-single.service"
listen_addr="127.0.0.1:8100"

require_cmd vault systemctl install ss || die "missing prerequisites"
[[ -f "${LAB_TLS_DIR}/vault-ca.pem" ]] || die "no Vault CA — run 'task vault' first"
[[ -S "${SWTPM_UNIX_SOCK}" ]] || die "no TPM socket — run 'task tpm' first"
as_lab_user_allow_fail vault read "auth/tpm/role/${role}" >/dev/null 2>&1 \
  || die "auth/tpm/role/${role} missing — run 'task config' first"

log_step "Workflow 2: one workload through a localhost Vault proxy"
log_info "The workload will use http://${listen_addr}; Vault Agent owns TPM login,"
log_info "token renewal and token injection."

systemctl stop vault-proxy-single vault-proxy@payments vault-proxy@analytics \
  >/dev/null 2>&1 || true
install -d -m 0755 /etc/vault-proxy /var/lib/vault-agent/single
install -d -m 0700 "${state_dir}"

if write_if_changed "${config}" <<EOF
# Generated by scripts/81_single_proxy.sh.
vault {
  address = "https://127.0.0.1:8200"
  ca_cert = "${LAB_TLS_DIR}/vault-ca.pem"
}

tpm_cert "workload_identity" {
  mount_path = "auth/tpm"
  role_name  = "${role}"

  tpm {
    device_path = "${SWTPM_UNIX_SOCK}"
  }

  csr {
    CN = "${device}.${domain}"
  }

  destination {
    path  = "${state_dir}"
    umask = "077"
  }
}

auto_auth {
  method "tpm" {
    mount_path = "auth/tpm"
    config = {
      tpm_cert  = "workload_identity"
      role_name = "${role}"
    }
  }
}

api_proxy {
  use_auto_auth_token = "force"
}

listener "tcp" {
  address     = "${listen_addr}"
  tls_disable = true
}
EOF
then
  log_info "Wrote ${config}"
fi

unit_changed=0
if write_if_changed "${unit}" <<'EOF'
# Generated by scripts/81_single_proxy.sh.
[Unit]
Description=Single-workload Vault Agent HTTP proxy (TPM auto-auth)
After=network-online.target vault-dev.service swtpm-unix-bridge.service
Wants=vault-dev.service swtpm-unix-bridge.service

[Service]
Type=simple
ExecStart=/usr/local/bin/vault agent -config=/etc/vault-proxy/single.hcl
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
then
  unit_changed=1
fi
(( unit_changed == 0 )) || systemctl daemon-reload

# Start with clean transient contexts and material. If Workflow 1 just attested,
# the server's per-EK limiter may reject the first acquisition; Agent retries it.
systemctl restart swtpm@device
wait_for_unit swtpm@device 30 || die "swtpm@device did not recover"
systemctl restart swtpm-unix-bridge
wait_for_unit swtpm-unix-bridge 15 || die "swtpm-unix-bridge did not recover"
as_lab_user tpm2_dictionarylockout -c || true
find "${state_dir}" -mindepth 1 -type f -delete 2>/dev/null || true

log_info "Starting Vault Agent; initial TPM certificate acquisition may wait for the EK rate limit."
systemctl enable vault-proxy-single >/dev/null
systemctl restart vault-proxy-single

for _ in $(seq 1 480); do
  recent="$(journalctl -u vault-proxy-single -n 40 --no-pager 2>/dev/null || true)"
  if ss -ltn | grep -q "${listen_addr}" \
    && printf '%s' "${recent}" | grep -q 'authentication successful'; then
    log_ok "http://${listen_addr} is ready with a ${role} TPM token"
    exit 0
  fi
  sleep 0.25
done

journalctl -u vault-proxy-single --no-pager -n 60 >&2 || true
die "single-workload proxy did not authenticate"
